"""Regenerate src/font-metrics.ts and src/font-data.ts from assets/Virgil.woff2.

The font file is embedded unmodified (no subsetting) so it keeps its OFL
Reserved Font Name "Virgil" legitimately. Advance widths for printable ASCII
are extracted so the renderer can wrap text deterministically without a DOM.

Usage (from the repository root):
    python -I packages/renderer-sketch/scripts/embed-font.py
Requires: fonttools, brotli.
"""
import base64
import hashlib
import pathlib
import sys

from fontTools.ttLib import TTFont

package = pathlib.Path(sys.argv[0]).resolve().parent.parent
font_path = package / "assets" / "Virgil.woff2"
out_path = package / "src" / "font-data.ts"
metrics_path = package / "src" / "font-metrics.ts"

raw = font_path.read_bytes()
font = TTFont(str(font_path))
units = font["head"].unitsPerEm
cmap = font.getBestCmap()
hmtx = font["hmtx"].metrics
fallback = hmtx[cmap[ord("n")]][0]

# Advance per code point 32..126, in thousandths of an em.
advances = []
for code in range(32, 127):
    glyph = cmap.get(code)
    width = hmtx[glyph][0] if glyph else fallback
    advances.append(round(width * 1000 / units))

average = round(sum(advances[1:]) / len(advances[1:]))

header = [
    "// Generated by scripts/embed-font.py. Do not edit by hand.",
    "// Virgil (c) 2021 - Present, Ellinor Rapp. SIL Open Font License 1.1.",
    "// Reserved Font Name \"Virgil\". See assets/Virgil-LICENSE.md.",
    "",
]
metrics = header + [
    "/** Advance widths for code points 32..126 in thousandths of an em. */",
    f"export const VIRGIL_ADVANCES: readonly number[] = [{', '.join(map(str, advances))}];",
    "",
    "/** Advance used for code points outside the ASCII table, in thousandths of an em. */",
    f"export const VIRGIL_FALLBACK_ADVANCE = {round(fallback * 1000 / units)};",
    "",
]
data = header + [
    f"export const VIRGIL_SHA256 = \"{hashlib.sha256(raw).hexdigest()}\";",
    "",
    "/** Unmodified Virgil WOFF2, base64 encoded. */",
    f"export const VIRGIL_WOFF2_BASE64 =\n  \"{base64.b64encode(raw).decode('ascii')}\";",
    "",
]
metrics_path.write_text("\n".join(metrics), encoding="utf-8")
out_path.write_text("\n".join(data), encoding="utf-8")
print(f"wrote src/font-metrics.ts and src/font-data.ts ({len(raw)} font bytes, {units} upm, avg advance {average}/1000 em)")
